"""Generate the report bundle for one adapter.

    python -m kepcmp.report --adapter rv --artifact-dir output/rv --out report/rv

Reads the ``signal.h5`` / ``null.h5`` that ``slurm/run_grid.sh`` wrote, runs the
reductions once, and writes ``REPORT.md``, ``findings.json``, ``provenance.json``,
``tables/`` and ``figures/``. The reduction CSVs land in ``tables/`` too, so
``--reuse-tables`` makes a second pass cheap while iterating on the prose.
"""

from __future__ import annotations

__all__ = ("main",)

import argparse
import shlex
import sys
from pathlib import Path

from kepcmp.report import amplitude, casestudy, nuisance
from kepcmp.report.data import load, write_provenance
from kepcmp.report.render import write_bundle

PREAMBLE = """
Generated by `python -m kepcmp.report`. Every number here comes from the reductions in
`kepcmp.reduce`, whose CSV outputs are in `tables/`; this document computes nothing of
its own. Regenerate with the command recorded in `provenance.json`.
""".strip()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact-dir", type=Path, required=True,
                        help="directory holding signal.h5 (and ideally null.h5)")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--adapter", choices=("rv", "gaia"), default=None,
                        help="default: whatever the artifact says wrote it")
    parser.add_argument("--fpr", type=float, default=0.01)
    parser.add_argument("--reuse-tables", action="store_true",
                        help="reuse reduction CSVs already in <out>/tables")
    parser.add_argument("--skip", nargs="*", default=(),
                        choices=("amplitude", "nuisance", "casestudy"),
                        help="omit a section (nuisance re-runs periodograms)")
    parser.add_argument("--nuisance-sims", type=int, default=24,
                        help="simulations in the nuisance-scale sweep")
    args = parser.parse_args(argv)

    out = args.out
    data = load(
        args.artifact_dir,
        adapter_name=args.adapter,
        cache_dir=out / "tables",
        reuse=args.reuse_tables,
        fpr=args.fpr,
    )

    sections = []
    if "amplitude" not in args.skip:
        sections.append(amplitude.build_section(data))
    if "nuisance" not in args.skip:
        sections.append(nuisance.build_section(data, n_sims=args.nuisance_sims))
    if "casestudy" not in args.skip:
        sections.append(casestudy.build_section(data))

    command = "python -m kepcmp.report " + " ".join(
        shlex.quote(a) for a in (argv if argv is not None else sys.argv[1:])
    )
    write_provenance(data, out / "provenance.json", command=command)
    report = write_bundle(
        sections,
        out,
        title=f"harv periodogram guidance from the kepmodel comparison "
              f"({data.adapter_name})",
        preamble=PREAMBLE,
        provenance={**data.provenance, "command": command},
    )
    print(f"wrote {report}")
    for sec in sections:
        print(f"  {sec.key:<12} {len(sec.tables)} tables, {len(sec.figures)} figures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
