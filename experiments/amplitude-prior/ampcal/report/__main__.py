"""Generate the report bundle for one adapter.

    python -m ampcal.report --adapter rv --artifact-dir output/rv --out report/rv

Reads the ``signal.h5`` that ``slurm/run_grid.sh`` wrote, runs the reduction once, and
writes ``REPORT.md``, ``findings.json``, ``provenance.json``, ``tables/`` and
``figures/``. The reduction CSV lands in ``tables/`` too, so ``--reuse-tables`` makes a
second pass cheap while iterating on the prose.
"""

from __future__ import annotations

__all__ = ("main",)

import argparse
import shlex
import sys
from pathlib import Path

from ampcal.report import amplitude, nuisance
from ampcal.report.data import load, write_provenance
from ampcal.report.render import write_bundle

PREAMBLE = """
Generated by `python -m ampcal.report`. Every number in the amplitude section comes from
`ampcal.reduce.calibrate`, whose CSV output is in `tables/`; that section computes
nothing of its own. The nuisance section runs its own periodograms, because the grid
never swept those scales. Regenerate with the command recorded in `provenance.json`.
""".strip()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact-dir", type=Path, required=True,
                        help="directory holding signal.h5")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--adapter", choices=("rv", "gaia"), default=None,
                        help="default: whatever the artifact says wrote it")
    parser.add_argument("--reuse-tables", action="store_true",
                        help="reuse the reduction CSV already in <out>/tables")
    parser.add_argument("--skip", nargs="*", default=(),
                        choices=("amplitude", "nuisance"),
                        help="omit a section (nuisance re-runs periodograms)")
    parser.add_argument("--nuisance-sims", type=int, default=24,
                        help="simulations in the nuisance-scale sweep")
    args = parser.parse_args(argv)

    out = args.out
    data = load(
        args.artifact_dir,
        adapter_name=args.adapter,
        cache_dir=out / "tables",
        reuse=args.reuse_tables,
    )

    sections = []
    if "amplitude" not in args.skip:
        sections.append(amplitude.build_section(data))
    if "nuisance" not in args.skip:
        sections.append(nuisance.build_section(data, n_sims=args.nuisance_sims))

    command = "python -m ampcal.report " + " ".join(
        shlex.quote(a) for a in (argv if argv is not None else sys.argv[1:])
    )
    write_provenance(data, out / "provenance.json", command=command)
    report = write_bundle(
        sections,
        out,
        title=f"harv periodogram amplitude-prior guidance ({data.adapter_name})",
        preamble=PREAMBLE,
        provenance={**data.provenance, "command": command},
    )
    print(f"wrote {report}")
    for sec in sections:
        print(f"  {sec.key:<12} {len(sec.tables)} tables, {len(sec.figures)} figures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
